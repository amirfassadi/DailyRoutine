import fs from 'node:fs';
import assert from 'node:assert/strict';
import ts from 'typescript';
const moduleCode=ts.transpileModule(fs.readFileSync('lib/coach.ts','utf8'),{compilerOptions:{target:ts.ScriptTarget.ES2022,module:ts.ModuleKind.ES2022}}).outputText;
const {adaptation,buildPlan,assessPlank,localDay}=await import('data:text/javascript;base64,'+Buffer.from(moduleCode).toString('base64'));
const ready={pain:false,sleep:7,fatigue:2};
assert.equal(adaptation([],ready).factor,.7);
assert.equal(adaptation([],{...ready,pain:true}).factor,0);
assert.equal(adaptation([],{...ready,fatigue:8}).rest,60);
assert.ok(Math.abs(adaptation([],{...ready,sleep:4}).factor-.56)<1e-10);
const sessions=[{id:'s1',kind:'session',day:'2026-10-08',createdAt:1,data:{complete:true,rpe:5,factor:.7,pain:false}},{id:'s2',kind:'session',day:'2026-10-09',createdAt:2,data:{complete:true,rpe:6,factor:.7,pain:false}}];
assert.equal(adaptation(sessions,ready).factor,.7);
const followups=sessions.map((s,i)=>({id:'f'+i,kind:'followup',day:'2026-10-10',createdAt:3+i,data:{sessionId:s.id,clear:true}}));
assert.equal(adaptation([...sessions,...followups],ready).factor,.75);
assert.equal(adaptation([...sessions,{...followups[1],data:{sessionId:'s2',clear:false}}],ready).factor,0);
assert.equal(buildPlan(.7,45).filter(x=>x.type==='straight')[0].seconds,70);
assert.equal(buildPlan(.7,45).filter(x=>x.type==='rest').length,6);
assert.equal(assessPlank([],640,480,'straight').status,'unknown');
assert.equal(assessPlank([],640,480,'diagonal').status,'unknown');
const pose=Array.from({length:33},()=>({x:0,y:0,visibility:0}));
for(const [i,x,y] of [[11,.2,.3],[13,.2,.5],[15,.2,.6],[23,.5,.4],[27,.8,.5]])pose[i]={x,y,visibility:.95};
assert.equal(assessPlank(pose,640,480,'straight').status,'aligned');
pose[23].y=.7;assert.equal(assessPlank(pose,640,480,'straight').status,'warning');
pose[23].visibility=.1;assert.equal(assessPlank(pose,640,480,'straight').status,'unknown');
assert.equal(localDay(new Date('2026-10-10T21:00:00Z')),'2026-10-11');
console.log('PASS: readiness, symptom stop, delayed symptoms, no premature increase, bounded increase, factor/rest, pose confidence, alignment, sagging, timezone.');
